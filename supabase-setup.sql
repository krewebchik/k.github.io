-- Выполнить один раз в Supabase → SQL Editor.
-- Создаёт таблицу content, включает защиту (RLS) и заполняет её
-- текущими текстами с сайта, чтобы после подключения ничего не "прыгнуло".

create table if not exists content (
  key         text primary key,
  value       text not null default '',
  label       text not null default '',
  section     text not null default '',
  type        text not null default 'text', -- 'text' или 'html' (html поддерживает переносы строк как <br>)
  sort_order  integer not null default 0,
  updated_at  timestamptz not null default now()
);

-- На случай, если таблицу уже создавали вручную без части колонок
alter table content add column if not exists value      text not null default '';
alter table content add column if not exists label      text not null default '';
alter table content add column if not exists section    text not null default '';
alter table content add column if not exists type       text not null default 'text';
alter table content add column if not exists sort_order integer not null default 0;
alter table content add column if not exists updated_at timestamptz not null default now();

alter table content enable row level security;

-- Читать тексты может кто угодно (это же публичная главная страница)
drop policy if exists "content_public_read" on content;
create policy "content_public_read"
  on content for select
  using (true);

-- Изменять тексты может только залогиненный пользователь (админ)
drop policy if exists "content_authenticated_update" on content;
create policy "content_authenticated_update"
  on content for update
  using (auth.role() = 'authenticated')
  with check (auth.role() = 'authenticated');

-- Автообновление updated_at при каждом изменении
create or replace function content_set_updated_at()
returns trigger as $$
begin
  new.updated_at = now();
  return new;
end;
$$ language plpgsql;

drop trigger if exists content_updated_at on content;
create trigger content_updated_at
  before update on content
  for each row execute function content_set_updated_at();

